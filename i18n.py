def get_locale():
    if has_request_context():
        locale = session.get("locale")
        if locale in SUPPORTED_LOCALES:
            return locale
        lang = request.args.get("lang")
        if lang in SUPPORTED_LOCALES:
            session["locale"] = lang
            return lang
    return Config.DEFAULT_LOCALE if Config.DEFAULT_LOCALE in SUPPORTED_LOCALES else "th"


def _(key, **kwargs):
    locale = get_locale()
    text = MESSAGES.get(locale, MESSAGES["th"]).get(key)
    if text is None:
        text = MESSAGES["th"].get(key, key)
    if kwargs:
        return text.format(**kwargs)
    return text


